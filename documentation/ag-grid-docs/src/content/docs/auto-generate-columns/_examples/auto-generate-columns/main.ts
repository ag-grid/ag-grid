let gridApi: GridApi;

const gridOptions: GridOptions = {
    autoGenerateColumnDefs: true,
    onFileInput: (event: FileInputEvent) => {
        const file = event.files[0];
        if (!file) return;
        const reader = new FileReader();
        reader.onload = (e) => {
            try {
                const rowData = parseCsv(e.target?.result as string);
                event.resolve(rowData);
            } catch {
                event.reject('Failed to parse CSV file');
            }
        };
        reader.readAsText(file);
    },
    processAutoGeneratedColumnDefs: (params) => {
        return params.colDefs.map((colDef) => {
            const sampleValue = params.rowData[0]?.[colDef.field!];
            if (!isNaN(Number(sampleValue))) {
                return { ...colDef, filter: 'agNumberColumnFilter' };
            }
            return { ...colDef, filter: 'agTextColumnFilter' };
        });
    },
};

function unquote(value: string): string {
    const trimmed = value.trim();
    if (trimmed.length >= 2 && trimmed[0] === '"' && trimmed[trimmed.length - 1] === '"') {
        return trimmed.slice(1, -1).replace(/""/g, '"');
    }
    return trimmed;
}

function parseCsv(csvText: string): Record<string, string | number>[] {
    const lines = csvText.trim().split('\n');
    const headers = lines[0].split(',').map(unquote);
    const rows: Record<string, string | number>[] = [];
    for (let i = 1, len = lines.length; i < len; ++i) {
        const values = lines[i].split(',').map(unquote);
        const row: Record<string, string | number> = {};
        for (let j = 0, hLen = headers.length; j < hLen; ++j) {
            const val = values[j];
            row[headers[j]] = isNaN(Number(val)) ? val : Number(val);
        }
        rows.push(row);
    }
    return rows;
}

function onLoadSampleData() {
    gridApi.setGridOption('rowData', parseCsv(sampleCsv));
}

function onClearData() {
    gridApi.setGridOption('rowData', null);
    gridApi.setGridOption('columnDefs', []);
}

document.addEventListener('DOMContentLoaded', () => {
    const gridDiv = document.querySelector<HTMLElement>('#myGrid')!;
    gridApi = createGrid(gridDiv, gridOptions);
});
