import { Component, signal } from '@angular/core';

import { AgGridAngular } from 'ag-grid-angular';
import type { IOverlayAngularComp } from 'ag-grid-angular';
import type { ColDef } from 'ag-grid-community';
import {
    ClientSideRowModelModule,
    ModuleRegistry,
    NumberFilterModule,
    TextFilterModule,
    ValidationModule,
} from 'ag-grid-community';
import type { IOverlayParams } from 'ag-grid-community';
import { AutoGenerateColumnsModule } from 'ag-grid-enterprise';

import './styles.css';

ModuleRegistry.registerModules([
    ClientSideRowModelModule,
    TextFilterModule,
    NumberFilterModule,
    AutoGenerateColumnsModule,
    ...(process.env.NODE_ENV !== 'production' ? [ValidationModule] : []),
]);

@Component({
    standalone: true,
    template: `
        <div class="file-drop-overlay">
            <span class="file-drop-icon">📄</span>
            <span>Drop a CSV file here to load data</span>
            <span class="file-drop-hint">or click "Load Sample CSV" above</span>
        </div>
    `,
})
export class FileDropOverlayComponent implements IOverlayAngularComp {
    agInit(params: IOverlayParams): void {}
}

