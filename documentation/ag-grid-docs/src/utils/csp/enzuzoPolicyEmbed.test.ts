// @vitest-environment jsdom
/**
 * Guards the ordering invariant in `public/scripts/enzuzo-policy-embed.js`: the
 * `createContextualFragment` patch that strips the vendor's inline <script>s must be installed
 * before the vendor loader is able to run, or the policy's three inline scripts reach the DOM and
 * the site CSP refuses them (AG-18194).
 *
 * That used to depend on the two <script src> tags racing each other, which is why the loader is
 * now injected by the script itself. These tests pin the guarantee rather than the timing, so the
 * loader cannot drift back to being a sibling tag unnoticed.
 */
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { beforeEach, describe, expect, it, vi } from 'vitest';

const EMBED_SCRIPT = fs.readFileSync(path.resolve(__dirname, '../../../public/scripts/enzuzo-policy-embed.js'), 'utf8');

const LOADER_SRC = 'https://app.enzuzo.com/scripts/cookies/0000-test-uuid';

/** The relevant part of what `cookies.astro` renders. */
function renderCookiesPage(): void {
    // innerHTML never executes scripts, so the host tag is inert here — as it is on the real page,
    // where it only carries the loader URL.
    document.body.innerHTML =
        '<div class="layout-max-width-small">' +
        '<div id="__enzuzo-root"></div>' +
        `<script data-policy-loader-src="${LOADER_SRC}"></script>` +
        '</div>';
}

function runEmbedScript(): void {
    vm.runInThisContext(EMBED_SCRIPT);
}

/** Stands in for the vendor loader's own insertion, which uses the same API. */
function injectPolicy(html: string): void {
    const range = document.createRange();
    range.setStart(document.body, 0);
    document
        .querySelector(`[${'data-policy-loader-src'}]`)
        ?.parentNode?.appendChild(range.createContextualFragment(html));
}

const POLICY_HTML =
    '<div ez-policy><h1>Cookie Policy</h1>' +
    '<script>window.ezphost = "app.enzuzo.com";</script>' +
    '<h2>How was this cookie policy generated?</h2>' +
    '<p>Generated by <a href="https://enzuzo.com">Enzuzo</a>.</p>' +
    '<h2>Kept section</h2><p>Body copy.</p></div>';

describe('Enzuzo cookie-policy embed', () => {
    const pristineCreateContextualFragment = Range.prototype.createContextualFragment;

    beforeEach(() => {
        Range.prototype.createContextualFragment = pristineCreateContextualFragment;
        renderCookiesPage();
    });

    it('injects the vendor loader as a sibling of its own tag, inside the content wrapper', () => {
        runEmbedScript();

        const loader = document.querySelector<HTMLScriptElement>(
            '.layout-max-width-small > script#__enzuzo-root-script'
        );
        expect(loader).not.toBeNull();
        expect(loader?.src).toBe(LOADER_SRC);
    });

    // The regression itself: whatever else changes, the patch has to be in place by the time the
    // loader element is created, because creating it is what starts the fetch that ends in an
    // insertion.
    it('installs the fragment patch before creating the loader element', () => {
        const realCreateElement = document.createElement.bind(document);
        let patchedWhenLoaderCreated: boolean | undefined;

        vi.spyOn(document, 'createElement').mockImplementation((tagName: string) => {
            if (tagName === 'script') {
                patchedWhenLoaderCreated =
                    Range.prototype.createContextualFragment !== pristineCreateContextualFragment;
            }
            return realCreateElement(tagName);
        });

        runEmbedScript();

        expect(patchedWhenLoaderCreated).toBe(true);
        vi.restoreAllMocks();
    });

    it('strips the vendor inline scripts out of the injected policy', async () => {
        runEmbedScript();
        injectPolicy(POLICY_HTML);

        expect(document.querySelectorAll('[ez-policy] script')).toHaveLength(0);
        await vi.waitFor(() => expect(document.querySelector('[ez-policy]')).not.toBeNull());
    });

    it('restores createContextualFragment once the policy has landed', async () => {
        runEmbedScript();
        expect(Range.prototype.createContextualFragment).not.toBe(pristineCreateContextualFragment);

        injectPolicy(POLICY_HTML);

        await vi.waitFor(() => expect(Range.prototype.createContextualFragment).toBe(pristineCreateContextualFragment));
    });

    it('removes the vendor self-promotional section and keeps the rest of the policy', async () => {
        runEmbedScript();
        injectPolicy(POLICY_HTML);

        await vi.waitFor(() => {
            const headings = [...document.querySelectorAll('[ez-policy] h1, [ez-policy] h2')].map(
                (heading) => heading.textContent
            );
            expect(headings).toEqual(['Cookie Policy', 'Kept section']);
        });
        expect(document.querySelector('[ez-policy] a[href*="enzuzo.com"]')).toBeNull();
    });
});
