#!/usr/bin/env node
/* eslint-disable no-console -- standalone CLI generator: writes rows to stdout / status to stderr */
// Expectation rows for markdown negotiation and per-content-class response headers, derived from
// each site's markdown page registry (the *_MARKDOWN_PAGE_GROUPS that also generate the Apache
// negotiation rule and its Vary scope).
//
// For one sample page per registry alternative, on the live site and on each archive build:
//   Accept: text/markdown -> 200 text/markdown twin, Vary: Accept, no agent Link header
//   browser Accept        -> 200 text/html (served via DirectoryIndex), Vary: Accept, the agent
//                            Link header, exactly one CSP, the security headers
// with the Cache-Control of its content class:
//   live HTML                         no-cache
//   released grid/charts archive      public, max-age=604800, s-maxage=31536000 (HTML and .md)
//   in-flight grid/charts archive     no-cache (HTML and .md)
//   studio archive                    no-cache (HTML and .md)
// Live .md Cache-Control is left unasserted: the target is an open decision (waf-finding.md §11).
//
// Usage: node gen-markdown-expectations.mjs <config.json>
//   config: [{ "base": "/charts", "kind": "live|released|in-flight|studio-archive",
//              "slug": "bar-series", "groups": ["<pattern>", ...] }, ...]
import { readFileSync } from 'node:fs';

import { Rows, samplesForGroupPattern } from './lib.mjs';

const configFile = process.argv[2];
if (!configFile) {
    console.error('usage: gen-markdown-expectations.mjs <config.json>');
    process.exit(2);
}
const LONG = 'public, max-age=604800, s-maxage=31536000';
const CACHE = {
    live: { html: 'no-cache', md: null },
    released: { html: LONG, md: LONG },
    'in-flight': { html: 'no-cache', md: 'no-cache' },
    'studio-archive': { html: 'no-cache', md: 'no-cache' },
};

const rows = new Rows();
for (const { base, kind, slug, groups, category } of JSON.parse(readFileSync(configFile, 'utf8'))) {
    const cache = CACHE[kind];
    if (!cache) {
        throw new Error(`unknown kind ${kind}`);
    }
    rows.section(category);
    const pages = new Set([`${base}/`]);
    for (const pattern of groups) {
        for (const sample of samplesForGroupPattern(pattern, slug)) {
            pages.add(`${base}/${sample}/`);
        }
    }
    const live = kind === 'live';
    for (const page of pages) {
        rows.add('www', page, 200, '', [
            'accept=md',
            'ct~^text/markdown',
            'vary+Accept',
            'link-describedby',
            ...(cache.md ? [`cc=${cache.md}`] : []),
            // live pages must never be noindexed at the edge (archives: open decision, §11)
            ...(live ? ['xrt=absent'] : []),
        ]);
        rows.add('www', page, 200, '', [
            'accept=html',
            'ct~^text/html',
            'vary+Accept',
            'link+describedby',
            'csp=1',
            'sec+',
            `cc=${cache.html}`,
            ...(live ? ['xrt=absent'] : []),
        ]);
    }
}
process.stdout.write(
    rows.toString([
        'GENERATED by gen-markdown-expectations.mjs from the markdown page registries - do not hand-edit; regenerate (see README).',
        `rows=${rows.count}`,
        `@min-rows ${Math.floor(rows.count * 0.95)}`,
    ])
);
console.error(`# markdown: ${rows.count} rows`);
