import markdoc from '@astrojs/markdoc';
import react from '@astrojs/react';
import sitemap from '@astrojs/sitemap';
import { defineConfig, fontProviders } from 'astro/config';
import dotenvExpand from 'dotenv-expand';
import { rm } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as sass from 'sass';
import { loadEnv } from 'vite';
import mkcert from 'vite-plugin-mkcert';
import svgr from 'vite-plugin-svgr';

import agCacheSitemap from '../../external/ag-website-shared/plugins/agCacheSitemap';
import agLinkChecker from '../../external/ag-website-shared/plugins/agLinkChecker';
import agMkcertPreview from '../../external/ag-website-shared/plugins/agMkcertPreview';
import agSitemapFilterNoindex from '../../external/ag-website-shared/plugins/agSitemapFilterNoindex';
import agSitemapLastmod from '../../external/ag-website-shared/plugins/agSitemapLastmod';
import agSourcemapCors from '../../external/ag-website-shared/plugins/agSourcemapCors';
import { SITEMAP_CACHE_DIR } from '../../external/ag-website-shared/src/constants';
import buildTime from './plugins/agBuildTime';
import agDevCsp from './plugins/agDevCsp';
import agDevExampleAssetCors from './plugins/agDevExampleAssetCors';
import agHotModuleReload from './plugins/agHotModuleReload';
import agHtaccessGen from './plugins/agHtaccessGen';
import agRedirectsChecker from './plugins/agRedirectsChecker';
import { getSitemapConfig } from './src/utils/sitemap';
import { urlWithBaseUrl } from './src/utils/urlWithBaseUrl';

const { NODE_ENV } = process.env;
const DEFAULT_BASE_URL = '/';
const PRODUCTION_SITE_URLS = ['https://ag-grid.com', 'https://www.ag-grid.com'];
const dotenv = {
    parsed: loadEnv(NODE_ENV, process.cwd(), ''),
};

/**
 * Environment variables used to modify the configuration of the server/build
 */
const {
    /**
     * Port used for servers
     */
    PORT,

    /**
     * Site url
     *
     * eg, `https://grid-staging.ag-grid.com`
     */
    PUBLIC_SITE_URL,

    /**
     * Base url used as a prefix to all urls
     *
     * eg, `/something` for site at `https://grid-staging.ag-grid.com/something`
     */
    PUBLIC_BASE_URL = DEFAULT_BASE_URL,

    /**
     * Use published packages in examples
     */
    PUBLIC_USE_PUBLISHED_PACKAGES,

    /**
     * Use packages for code
     */
    USE_PACKAGES,

    /**
     * Set up https server
     */
    PUBLIC_HTTPS_SERVER = '1',

    /**
     * Show debug logs in the terminal
     *
     * Used to hide logs that are annoying for most other devs
     */
    SHOW_DEBUG_LOGS,

    /**
     * Generate a `.htaccess` file for deployment
     *
     * Generated in `dist/.htaccess`
     */
    HTACCESS = 'false',

    /**
     * Check all redirects have a valid page generated by the build
     *
     * Checks the `to` paths in `src/utils/htaccess/redirects.ts`
     */
    CHECK_REDIRECTS = 'false',

    /**
     * Check all links have valid destinations generated by the build
     */
    CHECK_LINKS = 'false',

    /*
     * Select pages to build
     *
     * A comma separated list of pages to build to make it run faster
     */
    QUICK_BUILD_PAGES,

    /*
     * Disable example runner from rendering
     *
     * Useful for visual regression testing
     */
    DISABLE_EXAMPLE_RUNNER,

    /**
     * Charts sitemap index to merge
     */
    CHARTS_SITEMAP_INDEX_URL,

    /**
     * Charts robots.txt disallow json url to merge
     */
    CHARTS_ROBOTS_DISALLOW_JSON_URL,

    /**
     * Studio sitemap index to merge
     */
    STUDIO_SITEMAP_INDEX_URL,

    /**
     * Studio robots.txt disallow json url to merge
     */
    STUDIO_ROBOTS_DISALLOW_JSON_URL,

    /**
     * Upstream AI Toolkit API, proxied in dev to avoid browser CORS on localhost.
     * Only used when an example points `AI_API_URL` at the local `/ai-proxy` path.
     */
    AG_AI_API_UPSTREAM_URL = 'https://ai-api.ag-grid.com/api/openai/v1',

    /**
     * Dev token for the AI Toolkit proxy. When set, injected server-side by the dev
     * proxy so the token is never exposed to example browser code.
     */
    AG_AI_API_DEV_TOKEN,

    /**
     * Origin/Referer the dev proxy presents upstream. The AI proxy's access control is
     * primarily an origin allow-list, so set this to an allowed origin (e.g. the prod
     * site) if the upstream rejects the proxied request.
     */
    AG_AI_API_DEV_ORIGIN,
} = dotenvExpand.expand(dotenv).parsed;
console.log(
    'Astro configuration',
    JSON.stringify(
        {
            NODE_ENV,
            PORT,
            PUBLIC_SITE_URL,
            PUBLIC_BASE_URL,
            PUBLIC_HTTPS_SERVER,
            PUBLIC_USE_PUBLISHED_PACKAGES,
            USE_PACKAGES,
            SHOW_DEBUG_LOGS,
            HTACCESS,
            CHECK_LINKS,
            CHECK_REDIRECTS,
            QUICK_BUILD_PAGES,
            DISABLE_EXAMPLE_RUNNER,
            CHARTS_SITEMAP_INDEX_URL,
            CHARTS_ROBOTS_DISALLOW_JSON_URL,
            STUDIO_SITEMAP_INDEX_URL,
            STUDIO_ROBOTS_DISALLOW_JSON_URL,
        },
        null,
        2
    )
);

const plugins = [agSourcemapCors(), svgr(), agHotModuleReload(), agDevCsp(), agDevExampleAssetCors()];
if (NODE_ENV !== 'test') {
    plugins.push(mkcert()); // mkcert is not necessary for tests
}

const httpsEnabled = !['0', 'false'].includes(PUBLIC_HTTPS_SERVER);

// https://astro.build/config
export default defineConfig({
    fonts: [
        {
            provider: fontProviders.google(),
            name: 'IBM Plex Sans',
            cssVariable: '--font-ibm-plex-sans',
            weights: ['400', '500', '700'],
            styles: ['normal'],
        },
        {
            provider: fontProviders.google(),
            name: 'JetBrains Mono',
            cssVariable: '--font-jetbrains-mono',
            weights: ['400', '700'],
            styles: ['normal'],
        },
    ],
    site: PUBLIC_SITE_URL,
    base: PUBLIC_BASE_URL,
    security: {
        /**
         * Allow cross-origin dev-server fetches from external example hosts.
         *
         * Astro 6's secFetchMiddleware runs before Vite's CORS middleware and
         * returns 403 for unknown cross-origin subresource requests, so hosts
         * have to be allowed here as well as in `vite.server.cors.origin` below.
         */
        allowedDomains: [
            // Plunkr
            { hostname: 'run.plnkr.co', protocol: 'https' },
            // Codesandbox
            { hostname: '**.csb.app', protocol: 'https' },
        ],
    },
    devToolbar: {
        enabled: false,
    },
    vite: {
        plugins,
        server: {
            https: httpsEnabled,
            /**
             * Dev-only proxy for the AI Toolkit examples. The public example calls an absolute
             * `ai-api.ag-grid.com` URL, which browsers block from `localhost` on CORS. Point an
             * example's `AI_API_URL` at the same-origin `/ai-proxy` path (via `.env.local`) and
             * this forwards it upstream, adding the dev token server-side if one is configured.
             */
            proxy: {
                '/ai-proxy': {
                    target: AG_AI_API_UPSTREAM_URL,
                    changeOrigin: true,
                    rewrite: (path) => path.replace(/^\/ai-proxy/, ''),
                    configure: (proxy) => {
                        proxy.on('proxyReq', (proxyReq) => {
                            if (AG_AI_API_DEV_TOKEN) {
                                proxyReq.setHeader('Authorization', `Bearer ${AG_AI_API_DEV_TOKEN}`);
                            }
                            if (AG_AI_API_DEV_ORIGIN) {
                                proxyReq.setHeader('Origin', AG_AI_API_DEV_ORIGIN);
                                proxyReq.setHeader('Referer', `${AG_AI_API_DEV_ORIGIN}/`);
                            }
                        });
                    },
                },
            },
            cors: {
                /**
                 * CORS allow list for opening examples on external sites
                 */
                origin: [
                    // Plunkr
                    'https://run.plnkr.co',
                    // Codesandbox
                    /\.csb.app/,
                ],
            },
            headers: {
                // Content-Security-Policy is served per request by agDevCsp so
                // example paths can get a different policy from ordinary pages.
                'X-Content-Type-Options': 'nosniff',
            },
        },
        css: {
            preprocessorOptions: {
                scss: {
                    api: 'modern',
                    functions: {
                        'urlWithBaseUrl($url)': function (args) {
                            const sassUrl = args[0].assertString();
                            const url = sassUrl.toString().replaceAll(/['"]/g, '');
                            const urlWithBase = urlWithBaseUrl(url, PUBLIC_BASE_URL);

                            return new sass.SassString(urlWithBase);
                        },
                    },
                    loadPaths: ['../../external/ag-website-shared/src'],
                },
            },
        },
        optimizeDeps: {
            // Prevent vite from importing in content/docs folder
            exclude: ['vue', '@angular/common/http', '@angular/forms', '@angular/common', '@angular/platform-browser'],
        },
    },
    integrations: [
        buildTime(),
        react(),
        markdoc(),
        // Archive builds are fully noindex — omit sitemap generation and remove the /sitemap page.
        ...(!PUBLIC_BASE_URL?.includes('archive')
            ? [
                  sitemap(
                      getSitemapConfig({
                          chartsSitemap: CHARTS_SITEMAP_INDEX_URL,
                          studioSitemap: STUDIO_SITEMAP_INDEX_URL,
                      })
                  ),
                  agSitemapFilterNoindex({ enabled: PRODUCTION_SITE_URLS.includes(PUBLIC_SITE_URL) }),
                  agSitemapLastmod(),
                  agCacheSitemap({ cacheFolder: SITEMAP_CACHE_DIR }),
              ]
            : [
                  {
                      name: 'ag-archive-cleanup',
                      hooks: {
                          'astro:build:done': async ({ dir }) => {
                              await rm(join(fileURLToPath(dir), 'sitemap'), { recursive: true, force: true });
                          },
                      },
                  },
              ]),
        agHtaccessGen({ htaccessEnv: HTACCESS }),
        agRedirectsChecker({
            skip: CHECK_REDIRECTS !== 'true',
        }),
        agLinkChecker({ include: CHECK_LINKS === 'true' }),
        agMkcertPreview({ enabled: httpsEnabled }),
    ],
});
