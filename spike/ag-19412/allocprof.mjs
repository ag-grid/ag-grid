import { chromium } from 'playwright';
import fs from 'node:fs'; import path from 'node:path';
const [dir, mode] = process.argv.slice(2);
const tpl = fs.readFileSync(new URL('./repro.html', import.meta.url), 'utf8');
const htmlPath = path.join(path.resolve(dir), '_alloc.html');
fs.writeFileSync(htmlPath, tpl.replace('BUNDLE_DIR', 'file://' + path.resolve(dir)).replace('BUNDLE_FILE', 'ag-grid-enterprise.js'));
const browser = await chromium.launch({ args: ['--js-flags=--max-old-space-size=8192'] });
const page = await browser.newPage();
await page.goto('file://' + htmlPath);
const cdp = await page.context().newCDPSession(page);
await cdp.send('HeapProfiler.enable');
await cdp.send('HeapProfiler.startSampling', { samplingInterval: 4096, includeObjectsCollectedByMajorGC: true, includeObjectsCollectedByMinorGC: true });
await page.evaluate((m) => window.run(m), mode);
const { profile } = await cdp.send('HeapProfiler.stopSampling');
const self = new Map();
const walk = (n) => { const k = `${n.callFrame.functionName || '(anon)'}:${n.callFrame.lineNumber + 1}`; self.set(k, (self.get(k) ?? 0) + n.selfSize); for (const c of n.children) walk(c); };
walk(profile.head);
const total = [...self.values()].reduce((a, b) => a + b, 0);
console.log('total MB', (total / 1e6).toFixed(0));
for (const [k, v] of [...self].sort((a, b) => b[1] - a[1]).slice(0, 25)) console.log((v / 1e6).toFixed(1).padStart(7), 'MB', k);
await browser.close();
