import { chromium } from 'playwright';
import fs from 'node:fs'; import path from 'node:path';
const dir = path.resolve(process.argv[2]);
const htmlPath = path.join(dir, '_size.html');
fs.writeFileSync(htmlPath, `<!DOCTYPE html><html><head><script src="file://${dir}/ag-grid-enterprise.js"></script></head><body><div id="grid" style="height:600px"></div></body></html>`);
const browser = await chromium.launch({ args: ['--js-flags=--max-old-space-size=8192 --expose-gc', '--enable-precise-memory-info'] });
const page = await browser.newPage();
await page.goto('file://' + htmlPath);
const res = await page.evaluate(async () => {
  const mem = () => { gc(); gc(); return performance.memory.usedJSHeapSize; };
  const rows = []; let i = 0;
  for (let t = 0; t < 166667; t++) for (const s of ['A','B','C']) for (const x of ['M','F']) rows.push({ territory: 'T' + t, species: s, sex: x, i: i++ });
  const cols = (g) => [{ field: 'territory', rowGroup: g, hide: g }, { field: 'species', rowGroup: g, hide: g }, { field: 'sex' }, { field: 'i' }];
  const make = (g) => new Promise((resolve) => { const api = agGrid.createGrid(document.getElementById('grid'), { columnDefs: cols(g), rowData: rows, onFirstDataRendered: () => setTimeout(() => resolve(api), 100) }); });
  const out = {};
  const m0 = mem();
  let api = await make(false);
  out.flatMB = Math.round((mem() - m0) / 1e6);
  const leaf = api.getRowNode('0');
  out.leafOwnProps = Object.keys(leaf).length;
  out.leafNullishProps = Object.keys(leaf).filter((k) => leaf[k] == null || leaf[k] === false || leaf[k] === -1).length;
  api.destroy(); api = null;
  const m1 = mem();
  api = await make(true);
  out.groupedMB = Math.round((mem() - m1) / 1e6);
  const leaf2 = api.getRowNode('0');
  const group = leaf2.parent;
  out.groupOwnProps = Object.keys(group).length;
  out.groupNullishProps = Object.keys(group).filter((k) => group[k] == null || group[k] === false || group[k] === -1).length;
  out.leafGroupedOwnProps = Object.keys(leaf2).length;
  out.groupNullishNames = Object.keys(group).filter((k) => group[k] == null || group[k] === false || group[k] === -1).join(',');
  out.leafNullishNames = Object.keys(leaf2).filter((k) => leaf2[k] == null || leaf2[k] === false || leaf2[k] === -1).join(',');
  return out;
});
console.log(JSON.stringify(res, null, 1));
await browser.close();
