#!/bin/bash

if [ "$#" -lt 3 ]
  then
    echo "You must supply a grid version, a charts version & a host"
    echo "For example: ./scripts/deployments/prep_and_archive/uploadAndUnzipArchive.sh 36.1.0 14.1.0 user@host"
    echo ""
    echo "Both archives are exempted from caching while they are under test. Nothing undoes"
    echo "that explicitly: a production docs deploy emits an empty in-flight block, so going"
    echo "live restores normal caching on its own."
    exit 1
fi

function checkFileExists {
    file=$1
    if ! [[ -f "$file" ]]
    then
        echo "File [$file] doesn't exist - exiting script.";
        exit 1;
    fi
}

VERSION=$1
# The charts version cut alongside this grid version.
CHARTS_VERSION=$2
CURRENT_HOST=$3

export SSH_LOCATION=$SSH_FILE

# a few safety checks
if ! [[ "$VERSION" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]]
then
    echo "Version isn't in the expected format. Valid format is: Number.Number.number. For example 19.1.2";
    exit 1;
fi

if ! [[ "$CHARTS_VERSION" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]]
then
    echo "Charts version isn't in the expected format. Valid format is: Number.Number.Number. For example 14.1.0";
    exit 1;
fi

if [ -z "$SSH_LOCATION" ]
then
      echo "\$SSH_LOCATION is not set"
      exit 1;
fi

ARCHIVE="archive_`date +%Y%m%d`_$VERSION.tar.gz"


# delete dir if it exists - can ignore dir not found error
echo "ssh -i $SSH_LOCATION -p $SSH_PORT $CURRENT_HOST \"cd $GRID_ROOT_DIR/archive/ && [[ -d $VERSION ]] && rm -r $VERSION\""
ssh -i $SSH_LOCATION -p $SSH_PORT $CURRENT_HOST "cd $GRID_ROOT_DIR/archive/ && [[ -d $VERSION ]] && rm -r $VERSION"

# upload file
echo "ssh -i $SSH_LOCATION -p $SSH_PORT $CURRENT_HOST \"mkdir -p $GRID_ROOT_DIR/archive/$VERSION\""
ssh -i $SSH_LOCATION -p $SSH_PORT $CURRENT_HOST "mkdir -p $GRID_ROOT_DIR/archive/$VERSION"
echo "scp -i $SSH_LOCATION -P $SSH_PORT $ARCHIVE $CURRENT_HOST:$GRID_ROOT_DIR/archive/$VERSION/"
scp -i $SSH_LOCATION -P $SSH_PORT $ARCHIVE $CURRENT_HOST:$GRID_ROOT_DIR/archive/$VERSION/

# unzip archive
echo "ssh -i $SSH_LOCATION -p $SSH_PORT $CURRENT_HOST \"cd $GRID_ROOT_DIR/archive/$VERSION && tar -m -xf $ARCHIVE\""
ssh -i $SSH_LOCATION -p $SSH_PORT $CURRENT_HOST "cd $GRID_ROOT_DIR/archive/$VERSION && tar -m -xf $ARCHIVE"

#update folder permissions (default is 777 - change to 755)
echo "ssh -i $SSH_LOCATION -p $SSH_PORT $CURRENT_HOST \"chmod -R 755 $GRID_ROOT_DIR/archive/$VERSION\""
ssh -i $SSH_LOCATION -p $SSH_PORT $CURRENT_HOST "chmod -R 755 $GRID_ROOT_DIR/archive/$VERSION"

# --- in-flight archive caching exemption -------------------------------------------------
#
# A release candidate must serve fresh: without this the archive falls back to heuristic
# browser caching, which is ~10% of the page's age and so already exceeds five minutes an
# hour after a deploy - and it fails silently, because the tester holds that iteration's
# hashed assets too and sees a page that is internally consistent but stale.
#
# The rule has to live in the ROOT .htaccess: this deploy does not touch the root file
# otherwise, and a charts archive's own .htaccess is generated by the charts repo. The root
# is the only single place one edit covers both products, and charts release candidates
# deliberately do not touch it - a grid release candidate sets both.
#
# Nothing undoes this explicitly. A production docs build emits an EMPTY in-flight block, so
# going live restores normal caching on its own. The same is true of any docs deploy
# mid-cycle, which will drop the exemption - re-run this script if the cycle is still going.
#
# The live file is copied here, patched locally between its BEGIN/END markers, and copied
# back. The patcher rewrites only that block and exits non-zero if anything else would move,
# so the redirects, CSP and rewrites in the rest of the file cannot be disturbed.
PATCHER="$(dirname "$0")/../../uncached-archives.mjs"
checkFileExists "$PATCHER"

LIVE_HTACCESS=$(mktemp)
BACKUP="$GRID_ROOT_DIR/.htaccess.bak-$(date +%Y%m%d%H%M%S)"

echo "scp -i $SSH_LOCATION -P $SSH_PORT $CURRENT_HOST:$GRID_ROOT_DIR/.htaccess -> local"
if ! scp -i $SSH_LOCATION -P $SSH_PORT $CURRENT_HOST:$GRID_ROOT_DIR/.htaccess "$LIVE_HTACCESS"
then
    echo "Could not fetch the live root .htaccess - leaving it untouched.";
    rm -f "$LIVE_HTACCESS";
    exit 1;
fi

node "$PATCHER" "$LIVE_HTACCESS" set "$VERSION" "$CHARTS_VERSION" || { rm -f "$LIVE_HTACCESS"; exit 1; }

# Keep a timestamped copy on the box before overwriting, so a bad patch is one cp away from
# being undone without needing this script or a deploy.
echo "ssh -i $SSH_LOCATION -p $SSH_PORT $CURRENT_HOST \"cp $GRID_ROOT_DIR/.htaccess $BACKUP\""
ssh -i $SSH_LOCATION -p $SSH_PORT $CURRENT_HOST "cp $GRID_ROOT_DIR/.htaccess $BACKUP"

echo "scp -i $SSH_LOCATION -P $SSH_PORT local -> $CURRENT_HOST:$GRID_ROOT_DIR/.htaccess"
scp -i $SSH_LOCATION -P $SSH_PORT "$LIVE_HTACCESS" $CURRENT_HOST:$GRID_ROOT_DIR/.htaccess
rm -f "$LIVE_HTACCESS"

echo "Root .htaccess patched. Previous copy kept at $BACKUP"
echo "NOTE: a docs deploy resets the in-flight block. That is how the exemption is removed at"
echo "      GA, but it also means a mid-cycle docs deploy drops it - re-run this if so."
