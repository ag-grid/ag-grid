#!/usr/bin/env node
// Set or clear the in-flight archive exemption in a DEPLOYED root .htaccess, in place.
//
// An archive under release testing is redeployed for days and its fixes must appear within
// minutes, so it is exempted from the caching released archives get. That state lives only
// here: a docs build always emits an EMPTY block, because it has no way to know which
// archives are under test.
//
// The root file is the only single place one edit covers both products - a release candidate
// deploys the archive directory but not the root .htaccess, and a charts archive's own
// .htaccess is generated by the charts repo.
//
//   node scripts/uncached-archives.mjs <htaccess>                    # show current
//   node scripts/uncached-archives.mjs <htaccess> set   36.1.0 14.1.0
//   node scripts/uncached-archives.mjs <htaccess> clear 36.1.0 14.1.0
//
// set   overwrites whatever is there, so it is safe to re-run mid-cycle.
// clear only clears if BOTH versions match what is currently set, so a stale GA step cannot
//       end a cycle that has since moved on to different versions.
//
// Only the block between the BEGIN/END markers is ever rewritten - every other byte is
// preserved, and the script exits non-zero if that would not hold.
import { readFileSync, writeFileSync } from 'node:fs';

const BEGIN = '# BEGIN in-flight release archives - patched in place, do not edit by hand';
const END = '# END in-flight release archives';
const USAGE = 'usage: node scripts/uncached-archives.mjs <htaccess> [set|clear <grid> <charts>]';

const [file, action, grid, charts] = process.argv.slice(2);

if (!file) {
    console.error(USAGE);
    process.exit(2);
}
if (action && !['set', 'clear'].includes(action)) {
    console.error(USAGE);
    process.exit(2);
}
if (action && (!grid || !charts)) {
    console.error(`${action} needs both a grid and a charts version.\n${USAGE}`);
    process.exit(2);
}
for (const v of [grid, charts].filter(Boolean)) {
    if (!/^\d+\.\d+\.\d+$/.test(v)) {
        console.error(`'${v}' is not a version of the form 36.2.0`);
        process.exit(2);
    }
}

const source = readFileSync(file, 'utf8');
const b = source.indexOf(BEGIN);
const e = source.indexOf(END);
if (b < 0 || e < 0 || e < b) {
    console.error(`No in-flight marker block in ${file}.`);
    console.error('That file predates this feature, or is not the generated root .htaccess.');
    process.exit(1);
}

const GRID_PREFIX = '/archive/';
const CHARTS_PREFIX = '/charts/archive/';
const rule = (prefix, v) =>
    `Header set Cache-Control "no-cache" "expr=%{REQUEST_URI} =~ m#^${prefix}${v.replace(/\./g, '\\.')}/#"`;

const before = source
    .slice(b + BEGIN.length, e)
    .trim()
    .split('\n')
    .filter(Boolean);

// Read back the versions currently in the block, so clear can be guarded on them.
const versionIn = (prefix) => {
    const line = before.find((l) => l.includes(`m#^${prefix}`));
    const m = line?.match(new RegExp(`m#\\^${prefix.replace(/\//g, '\\/')}([0-9\\\\.]+)\\/#`));
    return m ? m[1].replace(/\\/g, '') : null;
};
const current = { grid: versionIn(GRID_PREFIX), charts: versionIn(CHARTS_PREFIX) };
const show = (g, c) => (g || c ? `grid ${g ?? 'none'}, charts ${c ?? 'none'}` : 'nothing in flight');

console.log(`current: ${show(current.grid, current.charts)}`);
if (!action) {
    process.exit(0);
}

if (action === 'clear' && (current.grid !== grid || current.charts !== charts)) {
    console.error(
        `\nREFUSING: ${show(current.grid, current.charts)} is in flight, not grid ${grid}, charts ${charts}.`
    );
    console.error('clear only ends the cycle it was given, so a stale GA step cannot end a newer one.');
    process.exit(1);
}

const after = action === 'set' ? [rule(GRID_PREFIX, grid), rule(CHARTS_PREFIX, charts)] : [];

const head = source.slice(0, b + BEGIN.length);
const tail = source.slice(e);
const next = head + (after.length ? '\n' + after.join('\n') : '') + '\n' + tail;

if (next === source) {
    console.log('\nAlready in that state - nothing to do.');
    process.exit(0);
}
// next is built from source's own head and tail, so this guards the construction, not a diff.
if (!next.startsWith(head) || !next.endsWith(tail)) {
    console.error('\nREFUSING: the change would touch bytes outside the marker block.');
    process.exit(1);
}

console.log('\nchanges, all inside the marker block:');
before.filter((l) => !after.includes(l)).forEach((l) => console.log(`  - ${l}`));
after.filter((l) => !before.includes(l)).forEach((l) => console.log(`  + ${l}`));
console.log(
    `\n${head.split('\n').length - 1} lines before the block and ${tail.split('\n').length - 1} after it are unchanged.`
);

writeFileSync(file, next);
console.log(`\napplied to ${file}`);
