import { BeanStub } from 'ag-grid-community';
import type { ColDef, NamedBean } from 'ag-grid-community';

export class AutoGenerateColumnsService extends BeanStub implements NamedBean {
    beanName = 'autoGenColsSvc' as const;

    public postConstruct(): void {
        this.generateColumns();
        this.addManagedPropertyListener('rowData', () => this.generateColumns());
    }

    private generateColumns(): void {
        const gos = this.gos;
        if (!gos.get('autoGenerateColumnDefs')) {
            return;
        }

        const rowData = gos.get('rowData');
        if (!rowData || rowData.length === 0) {
            return;
        }

        const firstRow = rowData[0];
        const keys = Object.keys(firstRow as object);
        let columnDefs: ColDef[] = [];
        for (let i = 0, len = keys.length; i < len; ++i) {
            columnDefs.push({ field: keys[i] });
        }

        const processCallback = gos.getCallback('processAutoGeneratedColumnDefs');
        if (processCallback) {
            columnDefs = processCallback({ colDefs: columnDefs, rowData });
        }

        gos.updateGridOptions({ options: { columnDefs }, source: 'optionsUpdated' });
    }
}
