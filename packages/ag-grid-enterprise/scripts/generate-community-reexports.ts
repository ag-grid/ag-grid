import * as fs from 'fs';
import * as path from 'path';
import * as ts from 'typescript';

const COMMUNITY_SRC = path.resolve(__dirname, '../../ag-grid-community/src');
const MAIN_PATH = path.join(COMMUNITY_SRC, 'main.ts');
const OUTPUT_PATH = path.resolve(__dirname, '../src/community-public.ts');

const sourceFileCache = new Map<string, ts.SourceFile>();

function getSourceFile(filePath: string): ts.SourceFile {
    if (!sourceFileCache.has(filePath)) {
        const text = fs.readFileSync(filePath, 'utf-8');
        sourceFileCache.set(filePath, ts.createSourceFile(path.basename(filePath), text, ts.ScriptTarget.Latest, true));
    }
    return sourceFileCache.get(filePath)!;
}

interface ExportInfo {
    name: string;
    isTypeOnly: boolean;
}

function getExportedDeclarationsFromFile(filePath: string): ExportInfo[] {
    const sourceFile = getSourceFile(filePath);
    const exports: ExportInfo[] = [];

    for (const stmt of sourceFile.statements) {
        const mods = ts.canHaveModifiers(stmt) ? ts.getModifiers(stmt) : undefined;
        const isExported = mods?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword);
        if (!isExported) {
            continue;
        }

        const isTypeOnly = ts.isInterfaceDeclaration(stmt) || ts.isTypeAliasDeclaration(stmt);

        if (
            ts.isClassDeclaration(stmt) ||
            ts.isInterfaceDeclaration(stmt) ||
            ts.isTypeAliasDeclaration(stmt) ||
            ts.isEnumDeclaration(stmt) ||
            ts.isFunctionDeclaration(stmt)
        ) {
            if (stmt.name) {
                exports.push({ name: stmt.name.text, isTypeOnly });
            }
        } else if (ts.isVariableStatement(stmt)) {
            for (const decl of stmt.declarationList.declarations) {
                if (ts.isIdentifier(decl.name)) {
                    exports.push({ name: decl.name.text, isTypeOnly: false });
                }
            }
        }
    }

    return exports;
}

function collectPublicExports(): ExportInfo[] {
    const sourceFile = getSourceFile(MAIN_PATH);
    const exports: ExportInfo[] = [];

    for (const stmt of sourceFile.statements) {
        if (!ts.isExportDeclaration(stmt) || !stmt.moduleSpecifier) {
            continue;
        }
        if (!ts.isStringLiteral(stmt.moduleSpecifier)) {
            continue;
        }

        const modulePath = stmt.moduleSpecifier.text;

        // Skip the internal re-export
        if (modulePath === './main-internal') {
            continue;
        }

        if (stmt.exportClause && ts.isNamedExports(stmt.exportClause)) {
            const stmtTypeOnly = stmt.isTypeOnly;
            for (const element of stmt.exportClause.elements) {
                const exportedName = element.name.text;
                const isTypeOnly = stmtTypeOnly || element.isTypeOnly;
                exports.push({ name: exportedName, isTypeOnly });
            }
        } else if (!stmt.exportClause) {
            // Wildcard re-export: expand to named exports
            const resolvedPath = path.resolve(COMMUNITY_SRC, modulePath + '.ts');
            const declarations = getExportedDeclarationsFromFile(resolvedPath);
            for (const decl of declarations) {
                exports.push(decl);
            }
        }
    }

    return exports;
}

function deduplicateExports(exports: ExportInfo[]): ExportInfo[] {
    const seen = new Map<string, ExportInfo>();
    for (const exp of exports) {
        const existing = seen.get(exp.name);
        if (!existing) {
            seen.set(exp.name, exp);
        } else if (existing.isTypeOnly && !exp.isTypeOnly) {
            // Value export wins over type-only (export { X } covers both)
            seen.set(exp.name, exp);
        }
    }
    return Array.from(seen.values());
}

function generateOutput(exports: ExportInfo[]): string {
    const deduplicated = deduplicateExports(exports);
    const typeExports: string[] = [];
    const valueExports: string[] = [];

    for (const exp of deduplicated) {
        if (exp.isTypeOnly) {
            typeExports.push(exp.name);
        } else {
            valueExports.push(exp.name);
        }
    }

    typeExports.sort();
    valueExports.sort();

    const lines: string[] = [
        '// DO NOT EDIT — generated by scripts/generate-community-reexports.ts',
        '// Run: npx tsx scripts/generate-community-reexports.ts',
        '',
    ];

    if (valueExports.length > 0) {
        lines.push('export {');
        for (const name of valueExports) {
            lines.push(`    ${name},`);
        }
        lines.push("} from 'ag-grid-community';");
        lines.push('');
    }

    if (typeExports.length > 0) {
        lines.push('export type {');
        for (const name of typeExports) {
            lines.push(`    ${name},`);
        }
        lines.push("} from 'ag-grid-community';");
        lines.push('');
    }

    return lines.join('\n');
}

const exports = collectPublicExports();
const output = generateOutput(exports);
fs.writeFileSync(OUTPUT_PATH, output, 'utf-8');

const typeCount = exports.filter((e) => e.isTypeOnly).length;
const valueCount = exports.filter((e) => !e.isTypeOnly).length;
console.log(`Generated ${OUTPUT_PATH}`);
console.log(`  ${valueCount} value exports, ${typeCount} type exports (${exports.length} total)`);
