import { _camelCaseToHumanText } from 'ag-stack';

import type { NamedBean } from '../context/bean';
import { BeanStub } from '../context/beanStub';
import type { ColDef, ColGroupDef } from '../entities/colDef';
import type { AutoGenerateColumnDefsOptions } from '../entities/gridOptions';
import { _isClientSideRowModel, _isServerSideRowModel } from '../gridOptionsUtils';
import { _isPlainObject } from '../utils/mergeDeep';
import { _isProtoField } from '../utils/value';

export class AutoGenerateColumnsService extends BeanStub implements NamedBean {
    beanName = 'autoGenColsSvc' as const;

    /** Under the Server-Side Row Model, `autoGenerateColumnDefs` is read once, at grid initialisation. */
    private serverSideOption: boolean | AutoGenerateColumnDefsOptions | undefined;
    private serverSideGenerated = false;

    public postConstruct(): void {
        const gos = this.gos;
        // Under the Server-Side Row Model, columns are generated from the first root-level response instead
        if (_isServerSideRowModel(gos)) {
            this.serverSideOption = gos.get('autoGenerateColumnDefs');
            return;
        }
        if (!_isClientSideRowModel(gos)) {
            return;
        }
        this.generateColumns(true);
        this.addManagedPropertyListener('rowData', () => this.generateColumns(false));
        this.addManagedPropertyListener('autoGenerateColumnDefs', () => this.generateColumns(false));
    }

    /**
     * Columns to start the grid with when none are supplied. The Server-Side Row Model needs to start without columns
     * so that it requests the rows the columns are generated from.
     */
    public getInitialColumnDefs(): (ColDef | ColGroupDef)[] | undefined {
        return this.serverSideOption ? [] : undefined;
    }

    /**
     * Called by the Server-Side Row Model with the rows of each root-level response. Columns are generated once, so
     * refetches after sort, filter or refresh keep the user's column state.
     */
    public onServerSideRootRowsLoaded(rowData: any[]): void {
        const optionValue = this.serverSideOption;
        if (!optionValue || this.serverSideGenerated) {
            return;
        }
        const columnDefs = this.createColumnDefs(rowData, optionValue);
        if (columnDefs) {
            this.serverSideGenerated = true;
            this.gos.updateGridOptions({ options: { columnDefs }, source: 'optionsUpdated' });
        }
    }

    private generateColumns(isInitial: boolean): void {
        const gos = this.gos;
        const optionValue = gos.get('autoGenerateColumnDefs');
        if (!optionValue) {
            return;
        }

        const columnDefs = this.createColumnDefs(gos.get('rowData') ?? [], optionValue);
        if (!columnDefs && isInitial) {
            return;
        }
        gos.updateGridOptions({ options: { columnDefs: columnDefs ?? [] }, source: 'optionsUpdated' });
    }

    /** Builds column definitions from the first plain-object row, or returns `undefined` when there is none. */
    private createColumnDefs(
        rowData: any[],
        optionValue: true | AutoGenerateColumnDefsOptions
    ): (ColDef | ColGroupDef)[] | undefined {
        const gos = this.gos;
        const config: AutoGenerateColumnDefsOptions = typeof optionValue === 'object' ? optionValue : {};
        let firstRow: Record<string, unknown> | undefined;
        for (let i = 0, len = rowData.length; i < len; ++i) {
            if (_isPlainObject(rowData[i])) {
                firstRow = rowData[i] as Record<string, unknown>;
                break;
            }
        }
        if (!firstRow) {
            return undefined;
        }
        let columnDefs = _buildColumnDefs(firstRow, undefined, config, !gos.get('suppressFieldDotNotation'));

        const processCallback = gos.getCallback('processAutoGeneratedColumnDefs');
        if (processCallback) {
            const result = processCallback({ columnDefs, rowData });
            // If the return type is an array we use that, otherwise assume they have mutated the existing columnDefs
            if (Array.isArray(result)) {
                columnDefs = result;
            }
        }
        return columnDefs;
    }
}

function _buildColumnDefs(
    obj: Record<string, unknown>,
    prefix: string | undefined,
    config: AutoGenerateColumnDefsOptions,
    dotNotation: boolean,
    visited: Set<object> = new Set()
): (ColDef | ColGroupDef)[] {
    const { objectValues = 'group', arrayValues = 'primitives', nullishValues = 'include' } = config;

    const keys = Object.keys(obj);
    const defs: (ColDef | ColGroupDef)[] = [];
    for (let i = 0, len = keys.length; i < len; ++i) {
        const key = keys[i];
        // with dot notation a dotted key is a nested path, so skip it when any segment is `__proto__`
        if (_isProtoField(key, dotNotation && key.includes('.') ? key.split('.') : null)) {
            continue;
        }
        const field = prefix ? `${prefix}.${key}` : key;
        const value = obj[key];

        if (_isPlainObject(value)) {
            if (visited.has(value)) {
                continue;
            }
            visited.add(value);
            if (objectValues === 'group') {
                const children = _buildColumnDefs(value, field, config, dotNotation, visited);
                if (children.length > 0) {
                    defs.push({ headerName: _camelCaseToHumanText(key) ?? key, children });
                }
            } else if (objectValues === 'flatten') {
                const children = _buildColumnDefs(value, field, config, dotNotation, visited);
                defs.push(...children);
            }
            continue;
        } else if (Array.isArray(value)) {
            if (arrayValues === 'skip' || (arrayValues === 'primitives' && !_isPrimitiveArray(value))) {
                continue;
            }
            defs.push(_makeLeafColDef(field, key, prefix, true));
            continue;
        } else if (value == null) {
            if (nullishValues !== 'include') {
                continue;
            }
        } else if (typeof value === 'function') {
            continue;
        }
        defs.push(_makeLeafColDef(field, key, prefix));
    }
    return defs;
}

function _makeLeafColDef(field: string, key: string, prefix: string | undefined, isArray?: boolean): ColDef {
    const colDef: ColDef = { field };
    if (prefix) {
        colDef.headerName = _camelCaseToHumanText(key) ?? key;
    }
    if (isArray) {
        colDef.cellDataType = false;
    }
    return colDef;
}

function _isPrimitiveArray(arr: unknown[]): boolean {
    if (arr.length === 0) {
        return false;
    }
    const first = arr[0];
    return first != null && !Array.isArray(first) && !_isPlainObject(first) && typeof first !== 'function';
}
